/**
 * @brief Define Action of S4
 *
 */

void task_BottomAction(void *pvParameters)
{
  while (1)
  {
    printf("Executing Task: task_BottomAction\n");
    S3_Action();
    S4_Action();
    vTaskDelay(50);
  }
}

void S3_Action(void)
{
  if (uS3status == BOTTOM_PUSH)
  {
    LED2_On();
  }
  else
  {
    /* invalid status of switch */
  }
}

/**
 * @brief Define Action of S4
 *
 */
void S4_Action(void)
{
  if (uS4status == BOTTOM_PUSH)
  {
    LED2_On();
  }
  else
  {
    /* invalid status of switch */
  }
}

// 外部中断1服务程序
void EXTI0_IRQHandler(void)
{
  LED2_On();
  Delay_ms(1000);
  LED2_Off();
  EXTI_ClearITPendingBit(EXTI_Line0); // 清除LINE0上的中断标志位  为下一次中断做准备
}

// 外部中断2服务程序
void EXTI2_IRQHandler(void)
{
  LED2_On();
  Delay_ms(1000);
  LED2_Off();
  EXTI_ClearITPendingBit(EXTI_Line2); // 清除LINE2上的中断标志位
}

