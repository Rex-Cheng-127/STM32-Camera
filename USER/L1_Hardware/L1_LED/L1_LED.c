/**
 * @brief Initialize for LED2
 *
 */
void LED2_Init(void)
{
  /* Declare GPIO Stucture */
  GPIO_InitTypeDef GPIO_InitStructure;

  /*Enable Clock Source of GPIO A */
  RCC_APB2PeriphClockCmd(RCC_APB2Periph_GPIOA, ENABLE);

  /* Config and Init PA1 (LED2)*/
  GPIO_InitStructure.GPIO_Pin = GPIO_Pin_1;         // Config Pin: Pin1 (Note: LED2 is at PA1)
  GPIO_InitStructure.GPIO_Mode = GPIO_Mode_Out_PP;  // Config Mode: Output (PP)
  GPIO_InitStructure.GPIO_Speed = GPIO_Speed_50MHz; // Config I/O Speed: 50 Mhz
  GPIO_Init(GPIOA, &GPIO_InitStructure);            // Initialize Channel PA with upside config
  // GPIO_ResetBits(GPIOA, GPIO_Pin_1);						          //Set PA1 to Low to Turn on LED2.
  GPIO_SetBits(GPIOA, GPIO_Pin_1); // Set PA1 to High to Turn off LED2.
}

/**
 * @brief Turn on LED2
 *
 */
void LED2_On(void)
{
  GPIO_ResetBits(GPIOA, GPIO_Pin_1); // Set PA1 to Low to Turn on LED2.
}

/**
 * @brief Turn off LED2
 *
 */
void LED2_Off(void)
{
  GPIO_SetBits(GPIOA, GPIO_Pin_1); // Set PA1 to High to turn off LED2.
}

void task_LifeLED2(void *pvParameters)
{

  while (1)
  {
    printf("Executing Task: task_LifeLED2\n");

    LED2_On();

    vTaskDelay(1000);

    LED2_Off();

    vTaskDelay(1000);
  }
}

